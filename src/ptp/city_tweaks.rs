
pub fn fold(s: &str) -> String {
    use finl_unicode::categories::CharacterCategories;
    use unicode_normalization::UnicodeNormalization;
    s.trim()
        .to_lowercase()
        .nfkd()
        .filter(|c| !c.is_mark())
        .collect()
}

